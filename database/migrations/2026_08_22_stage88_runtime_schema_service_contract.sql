-- ===========================================================================
-- SECTION F — stage76 safe-column ACL refresh for eld_devices
--
-- stage76 revokes table-level SELECT on eld_devices and rebuilds a COLUMN-level
-- grant covering every column except the five credential columns. It runs BEFORE
-- this file, so the eld_devices column SECTION B adds (last_sync_at, selected by
-- DvirHosEndpoints.cs) would carry no grant and 42501 for opstrax_app. Rebuild the
-- grant with stage76's own predicate — the forbidden columns stay forbidden, so
-- stage76's privilege assertions still hold.
-- ===========================================================================
DO $stage88_eld_safe_columns$
DECLARE safe_columns TEXT;
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='opstrax_app')
     OR to_regclass('public.eld_devices') IS NULL THEN
    RETURN;
  END IF;
  SELECT string_agg(quote_ident(column_name),',' ORDER BY ordinal_position)
    INTO safe_columns
    FROM information_schema.columns
   WHERE table_schema='public' AND table_name='eld_devices'
     AND column_name NOT IN (
       'api_key_hash','api_key_previous_hash','hmac_secret',
       'hmac_secret_encrypted','hmac_previous_secret_encrypted');
  IF safe_columns IS NULL THEN
    RAISE EXCEPTION 'Stage88 could not rebuild the stage76 safe eld_devices column grant';
  END IF;
  EXECUTE format('GRANT SELECT (%s) ON TABLE public.eld_devices TO opstrax_app', safe_columns);
END
