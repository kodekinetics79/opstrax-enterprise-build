-- ===========================================================================
-- SECTION E — RLS enrolment, tenant policies and least-privilege grants for the
--             47 tenant-scoped tables SECTION A creates.
--
-- FleetProductionReadinessService derives tenant_scope DYNAMICALLY from every
-- table carrying a bigint company_id/tenant_id, so a table created here without
-- RLS + FORCE + the exact stage58 policy pair + the peer grants would turn
-- /health/ready RED. This block replays the stage58 tenant-contract loop, scoped
-- to the tables above — same policy text, same grants, same sequence privileges.
-- Guarded (the 150e8c7 stage83/84/85 pattern): a database that has not yet run
-- the stage58 security cutover has no opstrax_security schema, and the RLS
-- reconciliation pass enrols these tables once it does.
-- ===========================================================================
DO $stage88_tenant_contract$
DECLARE
  rec       record;
  pol       record;
  seq_name  text;
  allow_ins boolean;
  allow_upd boolean;
  allow_del boolean;
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='opstrax_app')
     OR NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='opstrax_system')
     OR to_regprocedure('opstrax_security.current_tenant_id()') IS NULL THEN
    RAISE NOTICE 'Stage88: opstrax_security cutover not present — RLS enrolment deferred to the reconciliation pass';
    RETURN;
  END IF;

  FOR rec IN
    SELECT * FROM (VALUES
      ('alert_rules','company_id'),
      ('alert_follow_up_tasks','company_id'),
      ('billing_profiles','company_id'),
      ('billing_consolidation_runs','company_id'),
      ('customer_visibility','company_id'),
      ('customer_eta_snapshots','company_id'),
      ('dispatch_eligibility_config','company_id'),
      ('fin_config_sets','company_id'),
      ('fin_config_documents','company_id'),
      ('fin_config_change_log','company_id'),
      ('gl_periods','company_id'),
      ('gl_export_runs','company_id'),
      ('chart_of_accounts','company_id'),
      ('journal_entries','company_id'),
      ('journal_lines','company_id'),
      ('messaging_conversations','company_id'),
      ('messaging_messages','company_id'),
      ('tenant_billing_plan_items','company_id'),
      ('revrec_profiles','company_id'),
      ('revrec_fiscal_calendars','company_id'),
      ('revrec_fiscal_periods','company_id'),
      ('revenue_recognition_entries','company_id'),
      ('revrec_schedules','company_id'),
      ('revrec_schedule_lines','company_id'),
      ('safety_coaching_tasks','company_id'),
      ('sso_connections','company_id'),
      ('access_reviews','company_id'),
      ('access_review_items','company_id'),
      ('backup_verifications','company_id'),
      ('export_requests','company_id'),
      ('driver_detention_pay_policy','company_id'),
      ('pay_agreements','company_id'),
      ('settlement_statements','company_id'),
      ('settlement_lines','company_id'),
      ('settlement_payments','company_id'),
      ('tax_profiles','company_id'),
      ('tax_rules','company_id'),
      ('customer_tax_status','company_id'),
      ('seller_tax_registration','company_id'),
      ('invoice_tax_lines','company_id'),
      ('issued_invoice_tax_lines','company_id'),
      ('tenant_api_keys','company_id'),
      ('tenant_webhook_settings','company_id'),
      ('company_profile','company_id'),
      ('user_notification_prefs','company_id'),
      ('zatca_invoices','company_id'),
      ('module_records','company_id')
    ) AS t(table_name, tenant_column)
  LOOP
    CONTINUE WHEN to_regclass('public.'||rec.table_name) IS NULL;

    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', rec.table_name);
    EXECUTE format('ALTER TABLE public.%I FORCE ROW LEVEL SECURITY', rec.table_name);
    FOR pol IN SELECT policyname FROM pg_policies
                WHERE schemaname='public' AND tablename=rec.table_name
    LOOP
      EXECUTE format('DROP POLICY %I ON public.%I', pol.policyname, rec.table_name);
    END LOOP;
    EXECUTE format(
      'CREATE POLICY tenant_ticket_app ON public.%I AS PERMISSIVE FOR ALL TO opstrax_app '
      'USING (%I=(SELECT opstrax_security.current_tenant_id())) '
      'WITH CHECK (%I=(SELECT opstrax_security.current_tenant_id()))',
      rec.table_name, rec.tenant_column, rec.tenant_column);
    EXECUTE format(
      'CREATE POLICY system_control_plane ON public.%I AS PERMISSIVE FOR ALL TO opstrax_system '
      'USING (true) WITH CHECK (true)', rec.table_name);

    -- Least-privilege overrides that stage58 and the readiness tenant_privileges
    -- contract already pin for these table names; everything else takes the peer
    -- SELECT,INSERT,UPDATE,DELETE shape the other 193 tenant tables hold.
    SELECT lp.allow_insert, lp.allow_update, lp.allow_delete
      INTO allow_ins, allow_upd, allow_del
      FROM (VALUES
        ('access_review_items',true,true,false),
      ('access_reviews',true,true,false),
      ('backup_verifications',true,false,false),
      ('export_requests',true,true,false),
      ('sso_connections',true,true,false)
      ) AS lp(table_name, allow_insert, allow_update, allow_delete)
     WHERE lp.table_name = rec.table_name;

    EXECUTE format('GRANT SELECT,INSERT,UPDATE,DELETE ON TABLE public.%I TO opstrax_system', rec.table_name);
    EXECUTE format('REVOKE ALL ON TABLE public.%I FROM opstrax_app', rec.table_name);
    IF allow_ins IS NULL THEN
      EXECUTE format('GRANT SELECT,INSERT,UPDATE,DELETE ON TABLE public.%I TO opstrax_app', rec.table_name);
      allow_ins := true;
    ELSE
      EXECUTE format('GRANT SELECT ON TABLE public.%I TO opstrax_app', rec.table_name);
      IF allow_ins THEN EXECUTE format('GRANT INSERT ON TABLE public.%I TO opstrax_app', rec.table_name); END IF;
      IF allow_upd THEN EXECUTE format('GRANT UPDATE ON TABLE public.%I TO opstrax_app', rec.table_name); END IF;
      IF allow_del THEN EXECUTE format('GRANT DELETE ON TABLE public.%I TO opstrax_app', rec.table_name); END IF;
    END IF;

    FOR seq_name IN
      SELECT seq.oid::regclass::text
        FROM pg_class tbl
        JOIN pg_namespace n ON n.oid=tbl.relnamespace AND n.nspname='public'
        JOIN pg_depend d ON d.refobjid=tbl.oid AND d.refobjsubid>0 AND d.deptype IN ('a','i')
        JOIN pg_class seq ON seq.oid=d.objid AND seq.relkind='S'
       WHERE tbl.relname=rec.table_name
    LOOP
      EXECUTE format('GRANT USAGE,SELECT ON SEQUENCE %s TO opstrax_system', seq_name);
      EXECUTE format('REVOKE ALL ON SEQUENCE %s FROM opstrax_app', seq_name);
      IF allow_ins THEN
        EXECUTE format('GRANT USAGE,SELECT ON SEQUENCE %s TO opstrax_app', seq_name);
      END IF;
    END LOOP;
  END LOOP;

  -- Tables SECTION A creates that carry no bigint company_id/tenant_id are outside
  -- the tenant contract. They are operator/global ledgers: the system identity owns
  -- them and the restricted runtime identity gets nothing, matching stage58's
  -- treatment of the other global ledgers.
  FOR rec IN
    SELECT unnest(ARRAY['platform_invoice_lines', 'platform_invoice_sequences', 'platform_tax_registrations', 'platform_tax_rules', 'compliance_controls']) AS table_name
  LOOP
    CONTINUE WHEN rec.table_name = '' OR to_regclass('public.'||rec.table_name) IS NULL;
    EXECUTE format('REVOKE ALL ON TABLE public.%I FROM PUBLIC,opstrax_app', rec.table_name);
    EXECUTE format('GRANT SELECT,INSERT,UPDATE,DELETE ON TABLE public.%I TO opstrax_system', rec.table_name);
    FOR seq_name IN
      SELECT seq.oid::regclass::text
        FROM pg_class tbl
        JOIN pg_namespace n ON n.oid=tbl.relnamespace AND n.nspname='public'
        JOIN pg_depend d ON d.refobjid=tbl.oid AND d.refobjsubid>0 AND d.deptype IN ('a','i')
        JOIN pg_class seq ON seq.oid=d.objid AND seq.relkind='S'
       WHERE tbl.relname=rec.table_name
    LOOP
      EXECUTE format('REVOKE ALL ON SEQUENCE %s FROM PUBLIC,opstrax_app', seq_name);
      EXECUTE format('GRANT USAGE,SELECT ON SEQUENCE %s TO opstrax_system', seq_name);
    END LOOP;
  END LOOP;
END
