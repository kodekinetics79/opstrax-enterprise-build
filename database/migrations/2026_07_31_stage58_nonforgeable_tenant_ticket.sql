CREATE OR REPLACE FUNCTION opstrax_security.issue_tenant_ticket(
  p_tenant_id bigint,
  p_backend_pid integer,
  p_txid bigint,
  p_ttl_seconds integer DEFAULT 120
) RETURNS text
LANGUAGE plpgsql
VOLATILE
SECURITY DEFINER
SET search_path = pg_catalog, opstrax_security
AS $function$
DECLARE
  issued_nonce text;
  expires_epoch bigint;
  payload text;
  signature text;
  secret bytea;
BEGIN
  IF session_user <> 'opstrax_system' THEN
    RAISE EXCEPTION 'tenant ticket issuance requires opstrax_system' USING ERRCODE='42501';
  END IF;
  IF p_tenant_id IS NULL OR p_tenant_id<=0 OR p_backend_pid IS NULL OR p_backend_pid<=0
     OR p_txid IS NULL OR p_txid<=0 OR p_ttl_seconds IS NULL
     OR p_ttl_seconds<5 OR p_ttl_seconds>300 THEN
    RAISE EXCEPTION 'invalid tenant ticket binding' USING ERRCODE='22023';
  END IF;
  SELECT key_material INTO STRICT secret
  FROM opstrax_security.tenant_ticket_key WHERE singleton;
  issued_nonce := encode(public.gen_random_bytes(16),'hex');
  expires_epoch := extract(epoch FROM clock_timestamp())::bigint+p_ttl_seconds;
  payload := concat_ws(':','v1',p_tenant_id,p_backend_pid,p_txid,expires_epoch,issued_nonce);
  signature := encode(public.hmac(convert_to(payload,'UTF8'),secret,'sha256'),'hex');
  RETURN payload||':'||signature;
END
$function$;

CREATE OR REPLACE FUNCTION opstrax_security.current_tenant_id()
RETURNS bigint
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, opstrax_security
AS $function$
DECLARE
  ticket text;
  fields text[];
  payload text;
  secret bytea;
  ticket_tenant bigint;
  ticket_pid integer;
  ticket_txid bigint;
  expires_epoch bigint;
  supplied_signature bytea;
  expected_signature bytea;
BEGIN
  -- session_user is the authenticated identity even inside SECURITY DEFINER.
  IF session_user <> 'opstrax_app' THEN RETURN NULL; END IF;
  ticket := NULLIF(current_setting('app.tenant_ticket',true),'');
  IF ticket IS NULL OR length(ticket)>320 THEN RETURN NULL; END IF;
  fields := string_to_array(ticket,':');
  IF cardinality(fields)<>7 OR fields[1]<>'v1'
     OR fields[2]!~'^[1-9][0-9]{0,18}$'
     OR fields[3]!~'^[1-9][0-9]{0,9}$'
     OR fields[4]!~'^[1-9][0-9]{0,18}$'
     OR fields[5]!~'^[1-9][0-9]{0,18}$'
     OR fields[6]!~'^[0-9a-f]{32}$'
     OR fields[7]!~'^[0-9a-f]{64}$' THEN RETURN NULL; END IF;

  ticket_tenant := fields[2]::bigint;
  ticket_pid := fields[3]::integer;
  ticket_txid := fields[4]::bigint;
  expires_epoch := fields[5]::bigint;
  IF ticket_pid<>pg_backend_pid()
     OR ticket_txid<>txid_current()::bigint
     OR expires_epoch<extract(epoch FROM statement_timestamp())::bigint THEN RETURN NULL; END IF;

  SELECT key_material INTO STRICT secret
  FROM opstrax_security.tenant_ticket_key WHERE singleton;
  payload := array_to_string(fields[1:6],':');
  supplied_signature := decode(fields[7],'hex');
  expected_signature := public.hmac(convert_to(payload,'UTF8'),secret,'sha256');
  IF supplied_signature<>expected_signature THEN RETURN NULL; END IF;
  RETURN ticket_tenant;
EXCEPTION WHEN OTHERS THEN
  -- Malformed, overflowed, missing-key, or otherwise invalid tickets fail closed.
  RETURN NULL;
END
$function$;

REVOKE ALL ON FUNCTION opstrax_security.issue_tenant_ticket(bigint,integer,bigint,integer) FROM PUBLIC,opstrax_app;
REVOKE ALL ON FUNCTION opstrax_security.issue_tenant_ticket(bigint,integer,bigint,integer) FROM opstrax_system;
GRANT EXECUTE ON FUNCTION opstrax_security.issue_tenant_ticket(bigint,integer,bigint,integer) TO opstrax_system;
REVOKE ALL ON FUNCTION opstrax_security.current_tenant_id() FROM PUBLIC;
REVOKE ALL ON FUNCTION opstrax_security.current_tenant_id() FROM opstrax_app,opstrax_system;
GRANT EXECUTE ON FUNCTION opstrax_security.current_tenant_id() TO opstrax_app,opstrax_system;

CREATE OR REPLACE FUNCTION opstrax_security.special_policy_contract_valid()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY INVOKER
SET search_path = pg_catalog, public
AS $function$
WITH app_expr AS (
  SELECT table_name,column_name,prefix,command_name,policy_name,
    CASE command_name WHEN 'SELECT' THEN format('((%s IS NULL) OR (%s = ( SELECT opstrax_security.current_tenant_id() AS current_tenant_id)))',column_name,column_name)
      WHEN 'INSERT' THEN ''
      ELSE format('((%s IS NOT NULL) AND (%s = ( SELECT opstrax_security.current_tenant_id() AS current_tenant_id)))',column_name,column_name) END qual,
    CASE command_name WHEN 'SELECT' THEN '' WHEN 'DELETE' THEN ''
      ELSE format('((%s IS NOT NULL) AND (%s = ( SELECT opstrax_security.current_tenant_id() AS current_tenant_id)))',column_name,column_name) END check_expr
  FROM (VALUES ('roles','company_id','roles'),('report_catalog','tenant_id','report_catalog')) t(table_name,column_name,prefix)
  CROSS JOIN LATERAL (VALUES ('SELECT',prefix||'_app_select'),('INSERT',prefix||'_app_insert'),
    ('UPDATE',prefix||'_app_update'),('DELETE',prefix||'_app_delete')) c(command_name,policy_name)
), expected(table_name,policy_name,permissive,command_name,role_name,qual,check_expr) AS (
  SELECT table_name,policy_name,'PERMISSIVE',command_name,'opstrax_app',qual,check_expr FROM app_expr
  UNION ALL SELECT table_name,'system_control_plane','PERMISSIVE','ALL','opstrax_system','true','true'
    FROM (VALUES ('roles'),('report_catalog'),('role_permissions'),('user_mfa_status'),('user_locale_preferences')) s(table_name)
  UNION ALL VALUES
    ('role_permissions','role_permissions_app_select','PERMISSIVE','SELECT','opstrax_app','(EXISTS ( SELECT 1 FROM roles r WHERE ((r.id = role_permissions.role_id) AND ((r.company_id IS NULL) OR (r.company_id = ( SELECT opstrax_security.current_tenant_id() AS current_tenant_id))))))',''),
    ('role_permissions','role_permissions_app_insert','PERMISSIVE','INSERT','opstrax_app','', '(EXISTS ( SELECT 1 FROM roles r WHERE ((r.id = role_permissions.role_id) AND (r.company_id = ( SELECT opstrax_security.current_tenant_id() AS current_tenant_id)))))'),
    ('role_permissions','role_permissions_app_update','PERMISSIVE','UPDATE','opstrax_app','(EXISTS ( SELECT 1 FROM roles r WHERE ((r.id = role_permissions.role_id) AND (r.company_id = ( SELECT opstrax_security.current_tenant_id() AS current_tenant_id)))))','(EXISTS ( SELECT 1 FROM roles r WHERE ((r.id = role_permissions.role_id) AND (r.company_id = ( SELECT opstrax_security.current_tenant_id() AS current_tenant_id)))))'),
    ('role_permissions','role_permissions_app_delete','PERMISSIVE','DELETE','opstrax_app','(EXISTS ( SELECT 1 FROM roles r WHERE ((r.id = role_permissions.role_id) AND (r.company_id = ( SELECT opstrax_security.current_tenant_id() AS current_tenant_id)))))',''),
    ('user_mfa_status','tenant_ticket_app','PERMISSIVE','ALL','opstrax_app','(EXISTS ( SELECT 1 FROM users u WHERE ((u.id = user_mfa_status.user_id) AND (u.company_id = ( SELECT opstrax_security.current_tenant_id() AS current_tenant_id)))))','(EXISTS ( SELECT 1 FROM users u WHERE ((u.id = user_mfa_status.user_id) AND (u.company_id = ( SELECT opstrax_security.current_tenant_id() AS current_tenant_id)))))'),
    ('user_locale_preferences','tenant_ticket_app','PERMISSIVE','ALL','opstrax_app','(EXISTS ( SELECT 1 FROM users u WHERE ((u.id = user_locale_preferences.user_id) AND (u.company_id = ( SELECT opstrax_security.current_tenant_id() AS current_tenant_id)))))','(EXISTS ( SELECT 1 FROM users u WHERE ((u.id = user_locale_preferences.user_id) AND (u.company_id = ( SELECT opstrax_security.current_tenant_id() AS current_tenant_id)))))')
), actual AS (
  SELECT tablename table_name,policyname policy_name,permissive,cmd command_name,array_to_string(roles,',') role_name,
    regexp_replace(COALESCE(qual,''),'\s+',' ','g') qual,
    regexp_replace(COALESCE(with_check,''),'\s+',' ','g') check_expr
  FROM pg_policies WHERE schemaname='public'
    AND tablename IN ('roles','report_catalog','role_permissions','user_mfa_status','user_locale_preferences')
)
SELECT (SELECT count(*) FROM expected)=19 AND (SELECT count(*) FROM actual)=19
  AND (SELECT count(*)=5 AND bool_and(c.relrowsecurity AND c.relforcerowsecurity)
       FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
       WHERE n.nspname='public'
         AND c.relname IN ('roles','report_catalog','role_permissions','user_mfa_status','user_locale_preferences'))
  AND NOT EXISTS(SELECT * FROM expected EXCEPT SELECT * FROM actual)
  AND NOT EXISTS(SELECT * FROM actual EXCEPT SELECT * FROM expected)
$function$;
REVOKE ALL ON FUNCTION opstrax_security.special_policy_contract_valid() FROM PUBLIC,opstrax_app,opstrax_system;
GRANT EXECUTE ON FUNCTION opstrax_security.special_policy_contract_valid() TO opstrax_system;

CREATE OR REPLACE FUNCTION opstrax_security.generic_policy_contract_valid()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY INVOKER
SET search_path = pg_catalog, public
AS $function$
WITH tenant_scope AS (
  SELECT c.relname table_name,
    CASE WHEN c.relname='companies' THEN 'id'
         WHEN EXISTS(SELECT 1 FROM information_schema.columns x WHERE x.table_schema='public' AND x.table_name=c.relname AND x.column_name='company_id' AND x.data_type='bigint') THEN 'company_id'
         ELSE 'tenant_id' END tenant_col
  FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
  WHERE n.nspname='public' AND c.relkind IN ('r','p')
    AND c.relname NOT IN ('platform_invoices','gps_gateway_replay','platform_impersonation_sessions','roles','report_catalog')
    AND (c.relname='companies' OR EXISTS(SELECT 1 FROM information_schema.columns x
      WHERE x.table_schema='public' AND x.table_name=c.relname
        AND x.column_name IN ('company_id','tenant_id') AND x.data_type='bigint'))
), expected(table_name,policy_name,permissive,command_name,role_name,qual,check_expr) AS (
  SELECT table_name,'tenant_ticket_app','PERMISSIVE','ALL','opstrax_app',
    format('(%s = ( SELECT opstrax_security.current_tenant_id() AS current_tenant_id))',tenant_col),
    format('(%s = ( SELECT opstrax_security.current_tenant_id() AS current_tenant_id))',tenant_col)
  FROM tenant_scope
  UNION ALL SELECT table_name,'system_control_plane','PERMISSIVE','ALL','opstrax_system','true','true' FROM tenant_scope
), actual AS (
  SELECT p.tablename,p.policyname,p.permissive,p.cmd,array_to_string(p.roles,','),
    regexp_replace(COALESCE(p.qual,''),'\s+',' ','g'),
    regexp_replace(COALESCE(p.with_check,''),'\s+',' ','g')
  FROM pg_policies p JOIN tenant_scope t ON t.table_name=p.tablename
  WHERE p.schemaname='public'
)
SELECT (SELECT count(*) FROM actual)=(SELECT count(*) FROM expected)
  AND NOT EXISTS(SELECT * FROM expected EXCEPT SELECT * FROM actual)
  AND NOT EXISTS(SELECT * FROM actual EXCEPT SELECT * FROM expected)
$function$;
REVOKE ALL ON FUNCTION opstrax_security.generic_policy_contract_valid() FROM PUBLIC,opstrax_app,opstrax_system;
GRANT EXECUTE ON FUNCTION opstrax_security.generic_policy_contract_valid() TO opstrax_system;

-- Remove all inherited/default object capabilities, then rebuild the exact lanes.
REVOKE ALL PRIVILEGES ON ALL TABLES IN SCHEMA public FROM PUBLIC,opstrax_app,opstrax_system;
REVOKE ALL PRIVILEGES ON ALL SEQUENCES IN SCHEMA public FROM PUBLIC,opstrax_app,opstrax_system;

DO $definer_acl$
DECLARE rec record;
BEGIN
  -- Legacy SECURITY DEFINER functions are an alternate authorization surface.
  -- No runtime identity may execute one except the two locked ticket functions.
  FOR rec IN
    SELECT p.oid::regprocedure::text AS signature
    FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace
    WHERE p.prosecdef
      AND NOT (n.nspname='opstrax_security' AND p.proname IN ('issue_tenant_ticket','current_tenant_id'))
  LOOP
    EXECUTE format('REVOKE ALL ON FUNCTION %s FROM PUBLIC,opstrax_app,opstrax_system',rec.signature);
  END LOOP;
END
$definer_acl$;

DO $column_acl$
DECLARE rec record;
BEGIN
  -- Table ACL revocation does not remove independent column ACL entries.
  FOR rec IN
    SELECT n.nspname,c.relname,a.attname
    FROM pg_attribute a JOIN pg_class c ON c.oid=a.attrelid
    JOIN pg_namespace n ON n.oid=c.relnamespace
    WHERE n.nspname='public' AND c.relkind IN ('r','p') AND a.attnum>0
      AND NOT a.attisdropped AND a.attacl IS NOT NULL
  LOOP
    EXECUTE format('REVOKE ALL PRIVILEGES (%I) ON TABLE %I.%I FROM opstrax_app,opstrax_system',rec.attname,rec.nspname,rec.relname);
  END LOOP;
END
$column_acl$;

