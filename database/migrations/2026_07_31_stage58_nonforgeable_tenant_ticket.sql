DO $verify$
DECLARE violations text[];
BEGIN
  -- Managed Postgres (Neon/RDS/Cloud SQL) auto-grants the database owner ADMIN membership
  -- in every role created under it, and records the grant with the provider's internal
  -- superuser as grantor (e.g. Neon's cloud_admin). The customer-visible owner therefore
  -- CANNOT revoke it — REVOKE is a no-op warning — which made this contract unsatisfiable
  -- on every managed provider. That single membership grants no privilege the database
  -- owner does not already hold, so it is not an escalation edge. Keep both directions
  -- strict for every other principal: the runtime identity must still never be a member of
  -- anything, and no principal other than the database owner may SET ROLE into it.
  IF NOT EXISTS (SELECT 1 FROM pg_roles r WHERE r.rolname='opstrax_app' AND r.rolcanlogin AND NOT r.rolsuper AND NOT r.rolbypassrls AND NOT r.rolcreatedb AND NOT r.rolcreaterole AND NOT r.rolinherit AND NOT r.rolreplication
       AND NOT EXISTS(SELECT 1 FROM pg_auth_members m WHERE m.member=r.oid)
       AND NOT EXISTS(SELECT 1 FROM pg_auth_members m WHERE m.roleid=r.oid AND m.member<>(SELECT d.datdba FROM pg_database d WHERE d.datname=current_database())))
     OR NOT EXISTS (SELECT 1 FROM pg_roles r WHERE r.rolname='opstrax_system' AND r.rolcanlogin AND NOT r.rolsuper AND NOT r.rolbypassrls AND NOT r.rolcreatedb AND NOT r.rolcreaterole AND NOT r.rolinherit AND NOT r.rolreplication
       AND NOT EXISTS(SELECT 1 FROM pg_auth_members m WHERE m.member=r.oid)
       AND NOT EXISTS(SELECT 1 FROM pg_auth_members m WHERE m.roleid=r.oid AND m.member<>(SELECT d.datdba FROM pg_database d WHERE d.datname=current_database()))) THEN
    RAISE EXCEPTION 'Stage 58 runtime role attributes/memberships unsafe';
  END IF;
  IF EXISTS(SELECT 1 FROM pg_database d CROSS JOIN LATERAL aclexplode(COALESCE(d.datacl,acldefault('d',d.datdba))) acl
       WHERE d.datname=current_database() AND acl.grantee=0 AND acl.privilege_type IN ('CONNECT','TEMPORARY'))
     OR NOT has_database_privilege('opstrax_app',current_database(),'CONNECT')
     OR NOT has_database_privilege('opstrax_system',current_database(),'CONNECT')
     OR has_database_privilege('opstrax_app',current_database(),'CREATE,TEMPORARY')
     OR has_database_privilege('opstrax_system',current_database(),'CREATE,TEMPORARY')
     OR EXISTS(SELECT 1 FROM pg_namespace n CROSS JOIN LATERAL aclexplode(COALESCE(n.nspacl,acldefault('n',n.nspowner))) acl
       WHERE n.nspname='public' AND acl.grantee=0 AND acl.privilege_type IN ('USAGE','CREATE'))
     OR NOT has_schema_privilege('opstrax_app','public','USAGE')
     OR NOT has_schema_privilege('opstrax_system','public','USAGE')
     OR has_schema_privilege('opstrax_app','public','CREATE')
     OR has_schema_privilege('opstrax_system','public','CREATE') THEN
    RAISE EXCEPTION 'Stage 58 database/schema ACL envelope unsafe';
  END IF;
  IF EXISTS (
    SELECT 1 FROM pg_roles runtime
    WHERE runtime.rolname IN ('opstrax_app','opstrax_system') AND (
      EXISTS(SELECT 1 FROM pg_database d WHERE d.datdba=runtime.oid)
      OR EXISTS(SELECT 1 FROM pg_namespace n WHERE n.nspowner=runtime.oid)
      OR EXISTS(SELECT 1 FROM pg_class c WHERE c.relowner=runtime.oid)
      OR EXISTS(SELECT 1 FROM pg_proc p WHERE p.proowner=runtime.oid)
      OR EXISTS(SELECT 1 FROM pg_type t WHERE t.typowner=runtime.oid))) THEN
    RAISE EXCEPTION 'Stage 58 runtime identity owns database objects';
  END IF;
  IF (SELECT nspowner FROM pg_namespace WHERE nspname='opstrax_security')
       IN ((SELECT oid FROM pg_roles WHERE rolname='opstrax_app'),(SELECT oid FROM pg_roles WHERE rolname='opstrax_system'))
     OR (SELECT relowner FROM pg_class WHERE oid='opstrax_security.tenant_ticket_key'::regclass)
       IN ((SELECT oid FROM pg_roles WHERE rolname='opstrax_app'),(SELECT oid FROM pg_roles WHERE rolname='opstrax_system'))
     OR EXISTS(SELECT 1 FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace
       WHERE n.nspname='opstrax_security' AND p.proname IN ('issue_tenant_ticket','current_tenant_id')
         AND p.proowner IN ((SELECT oid FROM pg_roles WHERE rolname='opstrax_app'),(SELECT oid FROM pg_roles WHERE rolname='opstrax_system'))) THEN
