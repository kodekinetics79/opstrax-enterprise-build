DO $default_acl$
DECLARE rec record;
BEGIN
  FOR rec IN
    SELECT DISTINCT owner_role.rolname AS owner_name,d.defaclobjtype,grantee.rolname AS grantee_name
    FROM pg_default_acl d
    JOIN pg_namespace ns ON ns.oid=d.defaclnamespace AND ns.nspname='public'
    JOIN pg_roles owner_role ON owner_role.oid=d.defaclrole
    CROSS JOIN LATERAL aclexplode(d.defaclacl) acl
    JOIN pg_roles grantee ON grantee.oid=acl.grantee
    WHERE grantee.rolname IN ('opstrax_app','opstrax_system') AND d.defaclobjtype IN ('r','S')
  LOOP
    IF rec.defaclobjtype='r' THEN
      EXECUTE format('ALTER DEFAULT PRIVILEGES FOR ROLE %I IN SCHEMA public REVOKE ALL ON TABLES FROM %I',rec.owner_name,rec.grantee_name);
    ELSE
      EXECUTE format('ALTER DEFAULT PRIVILEGES FOR ROLE %I IN SCHEMA public REVOKE ALL ON SEQUENCES FROM %I',rec.owner_name,rec.grantee_name);
    END IF;
  END LOOP;
END
$default_acl$;

DO $tenant_contract$
DECLARE rec record; pol record; tenant_col text; seq_name text;
BEGIN
  FOR rec IN
    SELECT cls.relname AS table_name,
      CASE WHEN cls.relname='companies' THEN 'id'
           WHEN EXISTS (SELECT 1 FROM information_schema.columns c WHERE c.table_schema='public' AND c.table_name=cls.relname AND c.column_name='company_id' AND c.data_type='bigint') THEN 'company_id'
           ELSE 'tenant_id' END AS tenant_column
    FROM pg_class cls JOIN pg_namespace ns ON ns.oid=cls.relnamespace
    WHERE ns.nspname='public' AND cls.relkind IN ('r','p')
      AND cls.relname NOT IN ('platform_invoices','gps_gateway_replay','platform_impersonation_sessions')
      AND (cls.relname='companies' OR EXISTS (SELECT 1 FROM information_schema.columns c
        WHERE c.table_schema='public' AND c.table_name=cls.relname
          AND c.column_name IN ('company_id','tenant_id') AND c.data_type='bigint'))
  LOOP
    tenant_col:=rec.tenant_column;
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY',rec.table_name);
    EXECUTE format('ALTER TABLE public.%I FORCE ROW LEVEL SECURITY',rec.table_name);
    FOR pol IN SELECT policyname FROM pg_policies WHERE schemaname='public' AND tablename=rec.table_name LOOP
      EXECUTE format('DROP POLICY %I ON public.%I',pol.policyname,rec.table_name);
    END LOOP;
    EXECUTE format('CREATE POLICY tenant_ticket_app ON public.%I AS PERMISSIVE FOR ALL TO opstrax_app USING (%I=(SELECT opstrax_security.current_tenant_id())) WITH CHECK (%I=(SELECT opstrax_security.current_tenant_id()))',rec.table_name,tenant_col,tenant_col);
    EXECUTE format('CREATE POLICY system_control_plane ON public.%I AS PERMISSIVE FOR ALL TO opstrax_system USING (true) WITH CHECK (true)',rec.table_name);

    EXECUTE format('GRANT SELECT,INSERT,UPDATE,DELETE ON TABLE public.%I TO opstrax_system',rec.table_name);
    IF rec.table_name='companies' THEN
      EXECUTE 'GRANT SELECT,UPDATE ON TABLE public.companies TO opstrax_app';
    ELSE
      EXECUTE format('GRANT SELECT,INSERT,UPDATE,DELETE ON TABLE public.%I TO opstrax_app',rec.table_name);
    END IF;
    FOR seq_name IN
      SELECT seq.oid::regclass::text FROM pg_class tbl
      JOIN pg_namespace n ON n.oid=tbl.relnamespace AND n.nspname='public'
      JOIN pg_depend d ON d.refobjid=tbl.oid AND d.refobjsubid>0 AND d.deptype IN ('a','i')
      JOIN pg_class seq ON seq.oid=d.objid AND seq.relkind='S'
      WHERE tbl.relname=rec.table_name
    LOOP
      EXECUTE format('GRANT USAGE,SELECT ON SEQUENCE %s TO opstrax_system',seq_name);
      IF rec.table_name<>'companies' THEN EXECUTE format('GRANT USAGE,SELECT ON SEQUENCE %s TO opstrax_app',seq_name); END IF;
    END LOOP;
  END LOOP;

  -- Existing append/read-only and evidence contracts remain least privilege.
  FOR rec IN SELECT * FROM (VALUES
    ('authorization_decision_logs',true,false,false),('audit_logs',true,false,false),
    ('compliance_evidence',true,false,false),
