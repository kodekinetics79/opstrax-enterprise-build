-- Stage 58 -- non-forgeable, transaction-bound tenant authorization
--
-- A PostgreSQL custom GUC is not an authorization boundary: any connected role can
-- set app.current_tenant_id/app.platform_admin.  This terminal reconciliation
-- replaces every GUC-trusting tenant policy with two role-targeted policies:
--   * tenant_ticket_app      TO opstrax_app, derives the tenant only from a signed
--                            capability bound to PID + transaction + expiry; and
--   * system_control_plane   TO opstrax_system, the separately credentialed,
--                            restricted system lane.
--
-- No password is stored here. Operators provision independent strong passwords for
-- opstrax_app and opstrax_system out of band. The HMAC key is generated by this
-- owner migration and remains readable only by SECURITY DEFINER functions.

BEGIN;

CREATE EXTENSION IF NOT EXISTS pgcrypto;

DO $roles$
DECLARE rec record;
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='opstrax_app') THEN
    RAISE EXCEPTION 'Stage 58 requires opstrax_app; apply Stage 20 first';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='opstrax_system') THEN
    CREATE ROLE opstrax_system LOGIN NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION;
  END IF;
  -- Managed Postgres (Neon/RDS) never grants superuser, and naming the SUPERUSER /
  -- BYPASSRLS / REPLICATION attributes in ALTER ROLE requires it — even when the values
  -- already match, which would fail here with "permission denied to alter role". Only
  -- issue the ALTER for a role that actually deviates from the target shape; the
  -- verification block below still fails loudly if a role is wrong and uncorrectable.
  FOR rec IN
    SELECT rolname FROM pg_roles
    WHERE rolname IN ('opstrax_app','opstrax_system')
      AND (NOT rolcanlogin OR rolsuper OR rolbypassrls OR rolcreatedb
           OR rolcreaterole OR rolinherit OR rolreplication)
  LOOP
    EXECUTE format('ALTER ROLE %I LOGIN NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION', rec.rolname);
  END LOOP;

  FOR rec IN
    SELECT member_role.rolname AS member_name,granted.rolname AS granted_name
    FROM pg_auth_members membership
    JOIN pg_roles member_role ON member_role.oid=membership.member
    JOIN pg_roles granted ON granted.oid=membership.roleid
    WHERE member_role.rolname IN ('opstrax_app','opstrax_system')
  LOOP
    EXECUTE format('REVOKE %I FROM %I',rec.granted_name,rec.member_name);
  END LOOP;
  -- Also remove every principal that could inherit or SET ROLE into either
  -- runtime identity. Checking only memberships held by the runtime role leaves
  -- an incoming privilege-escalation edge.
  FOR rec IN
    SELECT member_role.rolname AS member_name,granted.rolname AS granted_name
    FROM pg_auth_members membership
    JOIN pg_roles member_role ON member_role.oid=membership.member
    JOIN pg_roles granted ON granted.oid=membership.roleid
    WHERE granted.rolname IN ('opstrax_app','opstrax_system')
  LOOP
    EXECUTE format('REVOKE %I FROM %I',rec.granted_name,rec.member_name);
  END LOOP;

  -- Exact database/schema envelope: connect + usage, never DDL or temp objects.
  EXECUTE format('REVOKE CONNECT,TEMPORARY ON DATABASE %I FROM PUBLIC',current_database());
  EXECUTE format('REVOKE CREATE,TEMPORARY ON DATABASE %I FROM opstrax_app,opstrax_system',current_database());
  EXECUTE format('GRANT CONNECT ON DATABASE %I TO opstrax_app,opstrax_system',current_database());
  REVOKE ALL ON SCHEMA public FROM PUBLIC;
  REVOKE ALL ON SCHEMA public FROM opstrax_app,opstrax_system;
  GRANT USAGE ON SCHEMA public TO opstrax_app,opstrax_system;
END
$roles$;

