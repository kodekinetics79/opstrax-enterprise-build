  END IF;
  IF EXISTS(SELECT 1 FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace
    WHERE p.prosecdef
      AND NOT (n.nspname='opstrax_security' AND ((p.proname='current_tenant_id' AND p.pronargs=0)
        OR (p.proname='issue_tenant_ticket' AND p.pronargs=4)))
      AND has_function_privilege('opstrax_system',p.oid,'EXECUTE')) THEN
    RAISE EXCEPTION 'Stage 58 system can execute a non-allowlisted SECURITY DEFINER function';
  END IF;
  IF EXISTS(SELECT 1 FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace
    WHERE n.nspname='opstrax_security' AND p.proname IN ('issue_tenant_ticket','current_tenant_id')
      AND (NOT p.prosecdef OR p.proowner<>(SELECT n2.nspowner FROM pg_namespace n2 WHERE n2.nspname='opstrax_security')
        OR p.proconfig IS DISTINCT FROM ARRAY['search_path=pg_catalog, opstrax_security']::text[])) THEN
    RAISE EXCEPTION 'Stage 58 ticket function owner/security/search_path drifted';
  END IF;
  IF has_table_privilege('opstrax_app','platform_admins','SELECT')
     OR has_table_privilege('opstrax_app','platform_sessions','SELECT')
     OR has_table_privilege('opstrax_app','platform_audit_log','SELECT')
     OR has_table_privilege('opstrax_app','platform_roles','SELECT')
     OR has_table_privilege('opstrax_app','platform_role_permissions','SELECT')
     OR has_table_privilege('opstrax_app','schema_migrations','SELECT')
     OR has_table_privilege('opstrax_app','service_heartbeats','SELECT')
     OR has_table_privilege('opstrax_app','service_run_history','SELECT')
     OR has_table_privilege('opstrax_app','telemetry_nonces','SELECT') THEN
    RAISE EXCEPTION 'Stage 58 app retains control-plane/system-ledger access';
  END IF;
  IF to_regclass('public.telemetry_stream_ticket_nonces') IS NOT NULL AND (
       NOT (SELECT relrowsecurity AND relforcerowsecurity FROM pg_class
            WHERE oid='public.telemetry_stream_ticket_nonces'::regclass)
       OR (SELECT count(*) FROM pg_policies
           WHERE schemaname='public' AND tablename='telemetry_stream_ticket_nonces')<>2
       OR NOT EXISTS (SELECT 1 FROM pg_policies
           WHERE schemaname='public' AND tablename='telemetry_stream_ticket_nonces'
             AND policyname='stream_ticket_nonce_app_insert' AND cmd='INSERT'
             AND roles='{opstrax_app}'::name[] AND qual IS NULL
             AND with_check LIKE '%opstrax_security.current_tenant_id()%')
       OR NOT EXISTS (SELECT 1 FROM pg_policies
           WHERE schemaname='public' AND tablename='telemetry_stream_ticket_nonces'
             AND policyname='system_control_plane' AND cmd='ALL'
             AND roles='{opstrax_system}'::name[] AND qual='true' AND with_check='true')
       OR NOT has_table_privilege('opstrax_app','telemetry_stream_ticket_nonces','INSERT')
