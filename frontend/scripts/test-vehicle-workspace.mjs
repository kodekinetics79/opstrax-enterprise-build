import assert from 'node:assert/strict';
import { observationAge, recentObservation, observedMotion, measuredNumber, deviceWorkspaceRoute } from '../src/utils/vehicleWorkspace.ts';
const now = Date.parse('2026-09-14T16:00:00Z');
assert.equal(observationAge(null, now), null);
assert.equal(observationAge('invalid', now), null);
assert.equal(observationAge('2026-09-14T16:01:00Z', now), null);
assert.equal(recentObservation('2026-09-14T15:59:00Z', now), true);
assert.equal(recentObservation('2026-09-14T15:50:00Z', now), false);
assert.equal(observedMotion(60, '2026-09-13T16:00:00Z', now), 'Current movement unknown');
assert.equal(observedMotion(60, '2026-09-14T16:01:00Z', now), 'Current movement unknown');
assert.equal(observedMotion(null, '2026-09-14T15:59:00Z', now), 'Current movement unknown');
assert.equal(observedMotion(60, '2026-09-14T15:59:00Z', now), 'Moving');
assert.equal(observedMotion(0, '2026-09-14T15:59:00Z', now), 'Stationary');
assert.equal(measuredNumber(null, 'mi'), 'Unknown');
assert.equal(measuredNumber('', 'mi'), 'Unknown');
assert.equal(measuredNumber(0, 'mi'), '0 mi');
assert.equal(deviceWorkspaceRoute(42, 'commands'), '/iot-devices?deviceId=42&deviceSection=commands');
assert.equal(deviceWorkspaceRoute(42, 'configuration'), '/iot-devices?deviceId=42&deviceSection=configuration');
assert.equal(deviceWorkspaceRoute(42, 'diagnostics'), '/iot-devices?deviceId=42&deviceSection=diagnostics');
console.log('Vehicle observation freshness, unknown measurements and exact device actions: passed');
